import { buildSync } from 'esbuild';
import { createRequire } from 'node:module';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const dir = mkdtempSync(join(tmpdir(), 'dugout-seed-'));
try {
  const output = join(dir, 'world.cjs');
  buildSync({
    entryPoints: ['apps/api/seed/world.ts'],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    outfile: output,
  });
  const { buildSeedWorld } = createRequire(import.meta.url)(output);
  const world = buildSeedWorld();
  const quote = (value) =>
    value === null || value === undefined
      ? 'NULL'
      : typeof value === 'number'
        ? String(value)
        : typeof value === 'boolean'
          ? value
            ? '1'
            : '0'
          : "'" + String(value).replaceAll("'", "''") + "'";
  const statements = [];
  function insert(table, columns, rows) {
    for (let i = 0; i < rows.length; i += 25)
      statements.push(
        `INSERT INTO ${table} (${columns.join(',')}) VALUES\n${rows
          .slice(i, i + 25)
          .map((row) => '(' + row.map(quote).join(',') + ')')
          .join(',\n')};`,
      );
  }
  insert(
    'leagues',
    [
      'id',
      'name',
      'country',
      'flag',
      'region',
      'label',
      'games',
      'level',
      'source',
      'season',
      'sort_order',
    ],
    world.leagues.map((l, i) => [
      l.id,
      l.name,
      l.country,
      l.flag,
      l.region,
      l.label,
      l.games,
      l.level,
      l.source,
      l.season,
      i,
    ]),
  );
  insert(
    'clubs',
    ['id', 'league_id', 'name', 'short', 'color', 'city', 'division', 'sort_order'],
    world.clubs.map((c, i) => [c.id, c.league, c.name, c.short, c.color, c.city, c.division, i]),
  );
  insert(
    'players',
    [
      'id',
      'club_id',
      'name',
      'original',
      'position',
      'age',
      'is_real',
      'country',
      'number',
      'contact',
      'power',
      'speed',
      'fielding',
      'stuff',
      'control',
      'potential',
      'salary',
      'years',
      'source',
      'sort_order',
    ],
    world.players.map((p, i) => [
      p.id,
      p.club === 'fa' ? null : p.club,
      p.name,
      p.original,
      p.pos,
      p.age,
      p.real,
      p.country,
      p.number,
      p.contact,
      p.power,
      p.speed,
      p.field,
      p.stuff,
      p.control,
      p.potential,
      p.salary,
      p.years,
      p.source,
      i,
    ]),
  );
  insert(
    'agents',
    ['id', 'name', 'agency', 'fee', 'priority', 'sort_order'],
    world.agents.map((a, i) => [a.id, a.name, a.agency, a.fee, a.priority, i]),
  );
  insert(
    'coach_candidates',
    ['id', 'name', 'role', 'skill', 'salary', 'style', 'sort_order'],
    world.coaches.map((c, i) => [c.id, c.name, c.role, c.skill, c.salary, c.style, i]),
  );
  insert(
    'catalog_meta',
    ['key', 'value'],
    [
      ['version', world.version],
      ['year', String(world.year)],
      ['roster_note', world.rosterNote],
    ],
  );
  const journal = JSON.parse(readFileSync('apps/api/drizzle/meta/_journal.json', 'utf8'));
  const entry = journal.entries.find((e) => e.tag.endsWith('_world_seed'));
  if (!entry) throw new Error('Generate a Drizzle custom world_seed migration first');
  const target = 'apps/api/drizzle/' + entry.tag + '.sql';
  writeFileSync(
    target,
    '-- Initial world catalog. Generated by npm run db:seed:generate.\n' +
      statements.join('\n--> statement-breakpoint\n') +
      '\n',
  );
  console.log(
    JSON.stringify({
      file: target,
      leagues: world.leagues.length,
      clubs: world.clubs.length,
      players: world.players.length,
      realPlayers: world.players.filter((p) => p.real).length,
      generatedPlayers: world.players.filter((p) => !p.real).length,
      agents: world.agents.length,
      coaches: world.coaches.length,
    }),
  );
} finally {
  rmSync(dir, { recursive: true, force: true });
}
